"""Generate sprites, NML and a review contact sheet for Modern Tycoon Trains.

Reads data/trains.yaml and the models in art/source/trains/, writes into
generated/ (disposable build output):

    generated/sprites/<art>.png      8bpp sprite strips (DOS palette)
    generated/modern_tycoon_trains.nml
    generated/contact_sheet.png      all directions and states on a schematic track

Run from the pack directory (build.sh does this).

SPDX-License-Identifier: GPL-2.0-only
"""
import importlib
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PACK = os.path.dirname(HERE)
sys.path[:0] = [HERE, os.path.join(PACK, 'art', 'source', 'trains')]

import render  # noqa: E402
from common import MATERIALS  # noqa: E402

GEN = os.path.join(PACK, 'generated')
CLIMATES = 'bitmask(CLIMATE_TEMPERATE, CLIMATE_ARCTIC, CLIMATE_TROPICAL)'


def spriteset_nml(name, png, rows):
	lines = [f'spriteset({name}, "{png}") {{']
	for direction, x, y, w, h, xoff, yoff in rows:
		lines.append(f'\t[{x}, {y}, {w}, {h}, {xoff}, {yoff}] // {direction}')
	lines.append('}')
	return '\n'.join(lines)


def te_coefficient(vehicle):
	"""Tractive effort coefficient = TE / (mass * g), two decimals, deterministic."""
	value = vehicle['tractive_effort_kn'] * 1000 / (vehicle['empty_mass_t'] * 1000 * 9.81)
	return f'{round(value, 2):.2f}'


def engine_item(v, ss):
	return f"""item(FEAT_TRAINS, {v['id']}, {v['numeric_id']}) {{
	property {{
		sprite_id: SPRITE_ID_NEW_TRAIN;
		name: string({v['strings']['name']});
		climates_available: {CLIMATES};
		introduction_date: date({v['intro_year']}, 1, 1);
		model_life: {v['model_life_years']};
		vehicle_life: {v['vehicle_life_years']};
		reliability_decay: {v['reliability_decay']};
		refittable_cargo_classes: bitmask();
		non_refittable_cargo_classes: bitmask();
		cargo_allow_refit: [];
		cargo_capacity: 0;
		loading_speed: 0;
		cost_factor: {v['cost_factor']};
		running_cost_factor: {v['running_cost_factor']};
		running_cost_base: RUNNING_COST_DIESEL;
		speed: {v['speed_kmh']} km/h;
		power: {v['power_kw']} kW;
		weight: {v['empty_mass_t']} ton;
		tractive_effort_coefficient: {te_coefficient(v)};
		track_type: RAIL;
		ai_special_flag: AI_FLAG_CARGO;
		engine_class: ENGINE_CLASS_DIESEL;
		visual_effect_and_powered: visual_effect_and_powered(VISUAL_EFFECT_DIESEL, 2, DISABLE_WAGON_POWER);
		dual_headed: 0;
		length: 8;
	}}
	graphics {{
		additional_text: return string({v['strings']['info']});
		purchase: {ss};
		{ss};
	}}
}}"""


def wagon_item(v, ss_empty, sg):
	return f"""item(FEAT_TRAINS, {v['id']}, {v['numeric_id']}) {{
	property {{
		sprite_id: SPRITE_ID_NEW_TRAIN;
		name: string({v['strings']['name']});
		climates_available: {CLIMATES};
		introduction_date: date({v['intro_year']}, 1, 1);
		model_life: {v['model_life_years']};
		vehicle_life: {v['vehicle_life_years']};
		reliability_decay: {v['reliability_decay']};
		refittable_cargo_classes: bitmask(CC_BULK);
		non_refittable_cargo_classes: bitmask(CC_PASSENGERS, CC_MAIL, CC_LIQUID, CC_REFRIGERATED, CC_ARMOURED);
		cargo_allow_refit: [];
		cargo_disallow_refit: [];
		default_cargo_type: {v['default_cargo']};
		cargo_capacity: {v['capacity']};
		loading_speed: {v['loading_speed']};
		cost_factor: {v['cost_factor']};
		running_cost_factor: {v['running_cost_factor']};
		running_cost_base: RUNNING_COST_STEAM;
		speed: {v['speed_kmh']} km/h;
		power: 0;
		weight: {v['empty_mass_t']} ton;
		track_type: RAIL;
		length: 8;
	}}
	graphics {{
		additional_text: return string({v['strings']['info']});
		purchase: {ss_empty};
		{sg};
	}}
}}"""


def main():
	data = yaml.safe_load(open(os.path.join(PACK, 'data', 'trains.yaml'), encoding='utf-8'))
	os.makedirs(os.path.join(GEN, 'sprites'), exist_ok=True)

	cargos = sorted({v['default_cargo'] for v in data['vehicles'] if v.get('default_cargo')})
	grf = data['grf']
	out = [
		'// Generated by tools/build_pack.py from data/trains.yaml. Do not edit.',
		'// SPDX-License-Identifier: GPL-2.0-only',
		f"""grf {{
	grfid: "{grf['grfid']}";
	name: string(STR_GRF_NAME);
	desc: string(STR_GRF_DESC);
	url: string(STR_GRF_URL);
	version: {grf['version']};
	min_compatible_version: {grf['min_compatible_version']};
}}""",
		'railtypetable { RAIL }',
		'cargotable { ' + ', '.join(cargos) + ' }',
	]
	review = []

	for v in data['vehicles']:
		art = importlib.import_module(v['art'])
		if v['kind'] == 'engine':
			sprites = render.render_set(art.MODEL, MATERIALS)
			if v.get('directional', True):
				diffs = render.check_directional(v['id'], sprites)
				print(f"{v['id']}: opposite directions differ by " + ', '.join(f'{a}/{b}={n}px' for (a, b), n in diffs.items()))
			png = f"generated/sprites/{v['art']}.png"
			rows = render.pack_strip(sprites, os.path.join(PACK, png))
			ss = f"ss_{v['id']}"
			out.append(spriteset_nml(ss, png, rows))
			out.append(engine_item(v, ss))
			review.append((f"{v['id']} ({v['numeric_id']})", sprites))
		else:
			sets = {}
			for state, model in (('empty', art.EMPTY), ('loaded', art.LOADED)):
				sprites = render.render_set(model, MATERIALS)
				png = f"generated/sprites/{v['art']}_{state}.png"
				rows = render.pack_strip(sprites, os.path.join(PACK, png))
				sets[state] = f"ss_{v['id']}_{state}"
				out.append(spriteset_nml(sets[state], png, rows))
				review.append((f"{v['id']} ({v['numeric_id']}) {state}", sprites))
			sg = f"sg_{v['id']}"
			out.append(f"""spritegroup {sg} {{
	loading: [{sets['empty']}, {sets['loaded']}];
	loaded: [{sets['empty']}, {sets['loaded']}];
}}""")
			out.append(wagon_item(v, sets['empty'], sg))

	with open(os.path.join(GEN, 'modern_tycoon_trains.nml'), 'w', encoding='utf-8') as f:
		f.write('\n\n'.join(out) + '\n')
	render.contact_sheet(review, os.path.join(GEN, 'contact_sheet.png'))
	print(f"wrote {len(data['vehicles'])} vehicles, {len(review)} sprite sets")


if __name__ == '__main__':
	main()
